/**
 * ThanaAlertService
 *
 * When a report is submitted with GPS coordinates, this service:
 * 1. Looks up the nearest police thana (police station) in Bangladesh
 * 2. Returns the thana name, district, and distance in km
 * 3. This information gets included in the NGO alert so responders
 *    know exactly which police station covers the incident area.
 *
 * How it works:
 * We store a hardcoded list of Bangladesh's major thana headquarters
 * with their GPS coordinates. Then we use the Haversine formula
 * (the same formula used to calculate distances on a sphere like Earth)
 * to find which thana is closest to the reported incident.
 *
 * This does NOT call any external API — it works fully offline.
 */
class ThanaAlertService
{
    /**
     * Find the nearest thana to a given GPS location.
     *
     * @param float $lat  Latitude of the incident
     * @param float $lng  Longitude of the incident
     * @return array      ['thana' => string, 'district' => string, 'distance_km' => float]
     */
    public function findNearestThana(float $lat, float $lng): array
    {
        $thanas  = $this->getBangladeshThanas();
        $nearest = null;
        $minDist = PHP_FLOAT_MAX;

        foreach ($thanas as $thana) {
            $dist = $this->haversine($lat, $lng, $thana['lat'], $thana['lng']);
            if ($dist < $minDist) {
                $minDist = $dist;
                $nearest = $thana;
            }
        }

        return [
            'thana'       => $nearest['thana']       ?? 'Unknown Thana',
            'district'    => $nearest['district']    ?? 'Unknown District',
            'division'    => $nearest['division']    ?? 'Unknown Division',
            'distance_km' => round($minDist, 2),
            'contact'     => $nearest['contact']     ?? null,
        ];
    }

    /**
     * Build a full Thana Alert message string for inclusion in NGO alerts.
     * This is the human-readable text that gets sent to NGOs.
     *
     * @param float  $lat
     * @param float  $lng
     * @param string $category  The crime category
     * @param string $severity  CRITICAL / HIGH / MEDIUM / LOW
     * @return string
     */
    public function buildAlertMessage(float $lat, float $lng, string $category, string $severity): string
    {
        $thana = $this->findNearestThana($lat, $lng);

        $categoryBn = match($category) {
            'corruption'        => 'দুর্নীতি (Corruption)',
            'child_abuse'       => 'শিশু নির্যাতন (Child Abuse)',
            'bribery'           => 'ঘুষ (Bribery)',
            'violence'          => 'সহিংসতা (Violence)',
            'harassment'        => 'হয়রানি (Harassment)',
            'drug_trafficking'  => 'মাদক (Drug Trafficking)',
            'extortion'         => 'চাঁদাবাজি (Extortion)',
            'land_grabbing'     => 'ভূমি দখল (Land Grabbing)',
            'police_misconduct' => 'পুলিশের অসদাচরণ (Police Misconduct)',
            default             => ucfirst(str_replace('_', ' ', $category)),
        };

        return implode("\n", [
            "═══════════════════════════════════════",
            "BIDROHI THANA ALERT — বিদ্রোহী",
            "═══════════════════════════════════════",
            "Severity    : {$severity}",
            "Category    : {$categoryBn}",
            "───────────────────────────────────────",
            "Nearest Thana   : {$thana['thana']}",
            "District        : {$thana['district']}",
            "Division        : {$thana['division']}",
            "Distance        : {$thana['distance_km']} km from incident",
            $thana['contact'] ? "Thana Contact   : {$thana['contact']}" : "",
            "───────────────────────────────────────",
            "This alert was auto-generated by BIDROHI AI.",
            "No personal identity of the reporter is stored.",
            "Report submitted anonymously via bidrohi.app",
            "═══════════════════════════════════════",
        ]);
    }

    /**
     * Haversine formula — calculates the great-circle distance between two
     * points on Earth given their latitude and longitude in decimal degrees.
     * Returns distance in kilometres.
     *
     * @param float $lat1  Point A latitude
     * @param float $lng1  Point A longitude
     * @param float $lat2  Point B latitude
     * @param float $lng2  Point B longitude
     * @return float       Distance in km
     */
    private function haversine(float $lat1, float $lng1, float $lat2, float $lng2): float
    {
        $earthRadius = 6371; // km

        $dLat = deg2rad($lat2 - $lat1);
        $dLng = deg2rad($lng2 - $lng1);

        $a = sin($dLat / 2) * sin($dLat / 2)
           + cos(deg2rad($lat1)) * cos(deg2rad($lat2))
           * sin($dLng / 2) * sin($dLng / 2);

        $c = 2 * atan2(sqrt($a), sqrt(1 - $a));

        return $earthRadius * $c;
    }

